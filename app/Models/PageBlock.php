<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\BelongsTo;


/*
|--------------------------------------------------------------------------
| Page Block Model
|--------------------------------------------------------------------------
|
| هر Page می‌تواند چندین Block داشته باشد.
|
| مثال:
|
| Page
|   |
|   ├── Hero Block
|   ├── Text Block
|   ├── Gallery Block
|   └── ...
|
| داده اصلی Block در ستون data ذخیره می‌شود.
| تنظیمات ظاهری در settings ذخیره می‌شود.
|
|--------------------------------------------------------------------------
*/


class PageBlock extends Model
{

    use HasFactory;



    /*
    |--------------------------------------------------------------------------
    | Fillable Fields
    |--------------------------------------------------------------------------
    |
    | ستون‌هایی که اجازه ذخیره دارند.
    |
    |--------------------------------------------------------------------------
    */


    protected $fillable = [

        'page_id',

        'type',

        'data',

        'settings',

        'sort_order',

        'is_active',

    ];




    /*
    |--------------------------------------------------------------------------
    | Casts
    |--------------------------------------------------------------------------
    |
    | تبدیل JSON دیتابیس به Array
    |
    |--------------------------------------------------------------------------
    */


    protected $casts = [


        'data' => 'array',


        'settings' => 'array',


        'is_active' => 'boolean',


    ];





    /*
    |--------------------------------------------------------------------------
    | Relationship
    |--------------------------------------------------------------------------
    |
    | هر Block متعلق به یک Page است.
    |
    |--------------------------------------------------------------------------
    */


    public function page(): BelongsTo
    {

        return $this->belongsTo(
            Page::class
        );

    }


}